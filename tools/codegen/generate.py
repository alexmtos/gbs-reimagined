"""Generate every derived artefact from the single sources of truth in schema/.

    uv run tools/codegen/generate.py           # write the generated files
    uv run tools/codegen/generate.py --check   # exit 1 if any generated file is stale (CI)

Sources and what they produce:
    schema/registers/tv5725.yaml -> firmware/src/chip/fields.gen.h
                                    firmware/src/chip/field_table.gen.cpp
                                    docs/reference/register-map.md
    schema/programs/*.yaml       -> firmware/src/chip/programs.gen.h
                                    firmware/src/chip/programs.gen.cpp
    schema/settings.yaml,        -> firmware/src/core/settings.gen.{h,cpp}
    schema/i18n/*.yaml              firmware/src/ui/strings.gen.cpp
                                    web/src/gen/settings.gen.ts, web/src/gen/i18n/*.gen.json
                                    docs/reference/settings.md

Generated files carry a header naming their source; never edit them by hand.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Callable
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "schema"
FW_CHIP = ROOT / "firmware/src/chip"
DOCS_REF = ROOT / "docs/reference"


def banner(source: str, comment: str = "//") -> str:
    return (
        f"{comment} GENERATED by tools/codegen/generate.py from {source}. Do not edit by hand:\n"
        f"{comment} change the source and run `uv run tools/codegen/generate.py`.\n"
    )


def load_yaml(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


# --------------------------------------------------------------------------- registers


def reg_key(seg: int, addr: int) -> str:
    return f"S{seg}_{addr:02X}"


def gen_registers() -> dict[Path, str]:
    src = "schema/registers/tv5725.yaml"
    db = load_yaml(SCHEMA / "registers/tv5725.yaml")
    fields: dict[str, dict] = db["fields"]
    regs: dict[str, dict] = db["registers"]

    out: dict[Path, str] = {}

    # fields.gen.h: one constexpr descriptor per field, typed by access.
    lines = [banner(src), "#pragma once", "", '#include "chip/field.h"', ""]
    lines += ["namespace gbsr::tv5725::fields {", ""]
    for name, f in fields.items():
        if f.get("signed"):
            kind = "SignedField"
        elif f["access"] == "ro":
            kind = "RoField"
        else:
            kind = "RwField"
        locus = f"{f['seg']}, 0x{f['addr']:02X}, {f['lsb']}, {f['width']}"
        lines.append(f"inline constexpr {kind} {name}{{{locus}}};")
    lines += ["", "} // namespace gbsr::tv5725::fields", ""]
    lines += [f"#define GBSR_TV5725_FIELD_COUNT {len(fields)}", ""]
    out[FW_CHIP / "fields.gen.h"] = "\n".join(lines)

    # field_table.gen.cpp: names in one PROGMEM blob plus a compact table, for the console.
    blob_parts: list[str] = []
    entries: list[str] = []
    offset = 0
    for name, f in sorted(fields.items()):
        flags = []
        if f["access"] == "rw":
            flags.append("kFieldWritable")
        if f.get("signed"):
            flags.append("kFieldSigned")
        flag_expr = " | ".join(flags) if flags else "0"
        locus = f"{f['seg']}, 0x{f['addr']:02X}, {f['lsb']}, {f['width']}"
        entries.append(f"    {{{offset}, {locus}, {flag_expr}}},")
        blob_parts.append(f'    "{name}\\0"')
        offset += len(name) + 1
    if offset > 0xFFFF:
        sys.exit("field name blob exceeds 64 KiB; widen FieldInfo::nameOffset")
    lines = [banner(src), '#include "chip/field_table.h"', ""]
    lines += ["namespace gbsr::tv5725 {", ""]
    lines += ["// Sorted by name, so lookups can bisect.", "const char kFieldNames[] PROGMEM ="]
    lines += blob_parts
    lines[-1] += ";"
    lines += ["", "const FieldInfo kFieldTable[] PROGMEM = {"]
    lines += entries
    lines += ["};", "", f"const uint16_t kFieldTableSize = {len(fields)};", ""]
    lines += ["} // namespace gbsr::tv5725", ""]
    out[FW_CHIP / "field_table.gen.cpp"] = "\n".join(lines)

    # register-map.md: the human reference.
    by_reg: dict[tuple[int, int], list[str]] = {}
    for name, f in fields.items():
        nbytes = (f["lsb"] + f["width"] + 7) // 8
        for i in range(nbytes):
            by_reg.setdefault((f["seg"], f["addr"] + i), []).append(name)
    ro_count = sum(1 for r in regs.values() if r["access"] == "ro")
    md = [
        f"<!-- GENERATED by tools/codegen/generate.py from {src}. Do not edit by hand: change the"
        " source and run `uv run tools/codegen/generate.py`. -->",
        "",
        "# TV5725 register map",
        "",
        f"{len(regs)} registers documented by the vendor ({ro_count} read-only), "
        f"{len(fields)} named fields. Pages refer to RD-5725-1.1 "
        "(see [datasheets](../hardware/datasheets.md)). A field spanning several bytes is listed "
        "under each byte it occupies.",
        "",
    ]
    for seg in range(6):
        md += [
            f"## Segment {seg}",
            "",
            "| Register | Block | Access | Pages | Fields |",
            "|---|---|---|---|---|",
        ]
        keys = sorted(
            {k for k in by_reg if k[0] == seg}
            | {(int(k[1]), int(k[3:], 16)) for k in regs if int(k[1]) == seg}
        )
        for key in keys:
            info = regs.get(reg_key(*key))
            block = info["block"] if info else "(undocumented)"
            access = info["access"].upper() if info else "?"
            pages = ", ".join(str(p) for p in info["pages"]) if info else ""
            names = ", ".join(f"`{n}`" for n in sorted(by_reg.get(key, [])))
            md.append(f"| {reg_key(*key)} | {block} | {access} | {pages} | {names} |")
        md.append("")
    out[DOCS_REF / "register-map.md"] = "\n".join(md)
    return out


# --------------------------------------------------------------------------- programs


def ident(program_id: str) -> str:
    return "".join(part.capitalize() for part in program_id.split("-"))


def gen_programs() -> dict[Path, str]:
    files = sorted((SCHEMA / "programs").glob("*.yaml"))
    programs = [load_yaml(p) for p in files]
    src = "schema/programs/*.yaml"
    out: dict[Path, str] = {}

    hdr = [banner(src), "#pragma once", "", "#include <stdint.h>", ""]
    hdr += ["namespace gbsr::tv5725 {", "", "enum class ProgramId : uint8_t {"]
    hdr += [f"    {ident(p['id'])}," for p in programs]
    hdr += ["    Count,", "};", "", "} // namespace gbsr::tv5725", ""]
    out[FW_CHIP / "programs.gen.h"] = "\n".join(hdr)

    body = [banner(src), '#include "chip/programs.h"', "", "namespace gbsr::tv5725 {", ""]
    body += ["namespace {", ""]
    for p in programs:
        name = ident(p["id"])
        records: list[str] = []
        size = 0
        for key, hexes in p["runs"].items():
            seg = int(key[1])
            start = int(key[3:], 16)
            values = [int(h, 16) for h in hexes.split()]
            records.append(
                f"    {seg}, 0x{start:02X}, {len(values)}, "
                + ", ".join(f"0x{v:02X}" for v in values)
                + ","
            )
            size += 3 + len(values)
        body += [f"// {p['id']}: {p['output']} ({p['source']['file']})"]
        body += [f"const uint8_t k{name}[] PROGMEM = {{"] + records + ["};", ""]
        body += [f'const char k{name}Name[] PROGMEM = "{p["id"]}";', ""]
        p["_size"] = size
    body += ["} // namespace", "", "const ProgramInfo kPrograms[] PROGMEM = {"]
    for p in programs:
        name = ident(p["id"])
        std = {"ntsc": "Standard::Ntsc", "pal": "Standard::Pal", "any": "Standard::Any"}[
            p["standard"]
        ]
        body.append(
            f"    {{ProgramId::{name}, {std}, k{name}Name, k{name}, {p['_size']}, {p['bytes']}}},"
        )
    body += ["};", "", "} // namespace gbsr::tv5725", ""]
    out[FW_CHIP / "programs.gen.cpp"] = "\n".join(body)
    return out


# --------------------------------------------------------------------------- settings


def gen_settings_all() -> dict[Path, str]:
    sys.path.insert(0, str(Path(__file__).parent))
    import gen_settings  # noqa: PLC0415 - sibling module, imported after the path is set

    return gen_settings.generate(ROOT, banner)


# --------------------------------------------------------------------------- driver

GENERATORS: list[Callable[[], dict[Path, str]]] = [gen_registers, gen_programs, gen_settings_all]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()

    stale: list[Path] = []
    for generator in GENERATORS:
        for path, content in generator().items():
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current == content:
                continue
            if args.check:
                stale.append(path)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        print("run `uv run tools/codegen/generate.py` and commit the result")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
