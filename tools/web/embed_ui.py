"""PlatformIO pre-build script: embed the gzip web UI into the firmware (ADR 0008).

Reads ../web/dist/index.html.gz (built by `pnpm -C web build`) and writes
$BUILD_DIR/generated/net/ui_bundle.gen.h with the bytes in PROGMEM and an ETag. Without a web build
it embeds a one-line page saying how to build the UI, so firmware work does not need Node.js; CI
always builds the web first (ci.yml, job "firmware").
"""

from __future__ import annotations

import gzip
import hashlib
from pathlib import Path

Import("env")  # noqa: F821 — provided by PlatformIO/SCons

STUB = (
    b"<!doctype html><meta charset=utf-8><title>GBS Reimagined</title>"
    b"<p>The web interface was not built into this firmware. Run <code>pnpm -C web build</code> "
    b"and build the firmware again. The serial console works meanwhile."
)


def render(data: bytes, stub: bool) -> str:
    etag = hashlib.sha256(data).hexdigest()[:16]
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 24]) + ",")
    body = "\n".join(rows)
    return f"""// GENERATED by tools/web/embed_ui.py from web/dist/index.html.gz while building.
#pragma once

#include <stdint.h>

#include "platform/progmem.h"

namespace gbsr::net::ui {{

constexpr bool kStub = {"true" if stub else "false"};
constexpr uint32_t kSize = {len(data)};
constexpr char kEtag[] = "\\"{etag}\\"";

alignas(4) static const uint8_t kGzip[] PROGMEM = {{
{body}
}};

}} // namespace gbsr::net::ui
"""


def main() -> None:
    project = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
    bundle = project.parent / "web" / "dist" / "index.html.gz"
    if bundle.exists():
        data, stub = bundle.read_bytes(), False
    else:
        data, stub = gzip.compress(STUB, compresslevel=9, mtime=0), True
        print("embed_ui: web/dist/index.html.gz not found; embedding the placeholder page")
    out_dir = Path(env.subst("$BUILD_DIR")) / "generated"  # noqa: F821
    header = out_dir / "net" / "ui_bundle.gen.h"
    text = render(data, stub)
    if not header.exists() or header.read_text(encoding="utf-8") != text:
        header.parent.mkdir(parents=True, exist_ok=True)
        header.write_text(text, encoding="utf-8")
    env.Append(CPPPATH=[str(out_dir)])  # noqa: F821


main()
